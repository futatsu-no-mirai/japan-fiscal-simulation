FOOD_PERMANENT = -1.4   # 食料品を恒久ゼロにした場合の減収（兆円/年）
                        # 既定路線は 8%→1% を2年で -1.2兆円。8pt分に引き伸ばして -1.4


def party_extra(p: dict, base: dict) -> dict:
    """党の公約を、モデルのパラメータに移す"""
    extra = dict(base)
    if p["food"]:
        extra["food_vat_cut"] = FOOD_PERMANENT
        extra["food_vat_years"] = 35
    extra["imm_dep"] = extra.get("imm_dep", 0.0) + p["genzai"]
    if p["iryo"]:
        extra["iryo"] = p["iryo"]
    return extra


def party_scenario(p: dict, boost: float, reform: bool = False) -> dict:
    """
    その党の税制案を、02節の年表と同じ計算に入れる（v6_yen.run_inf）。
      reform=False … 既定路線と同じ前提。生産性・投資・労働参加は現状のまま
      reform=True  … 本計画の改革（生産性+0.51pt、投資4.0%、労働参加+3.5%）を併走させる

    減税は vat_start=0 から10年かけて到達する扱い。即時実施より財政には有利で、
    つまり各党に最大限有利な条件で計算している。
    """
    extra = party_extra(p, B_ if reform else KIM)
    step = 0.0 if p["vat"] is None else (p["vat"] - 10.0)
    kw = dict(inv=0.040, part=0.035) if reform else {}
    return run_inf(0.020, vat_step=step, vat_start=0, boost=boost,
                   extra=extra, **kw)


def solve_with_cut(p: dict, boost: float) -> float:
    """その党の減税を恒久的な歳入減として残したまま、財政を止める消費税率を解く"""
    cut = 0.0
    if p["vat"] is not None:
        cut += (p["vat"] - 10.0) * VATPT      # 消費税の引き下げ分（兆円/年）
    if p["food"]:
        cut += FOOD_PERMANENT
    extra = dict(B_)
    extra["imm_dep"] = extra.get("imm_dep", 0.0) + cut + p["genzai"]
    if p["iryo"]:
        extra["iryo"] = p["iryo"]
    return 10.0 + solve(boost, extra)


